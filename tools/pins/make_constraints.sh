#!/usr/bin/env bash
# Regenerates deploy/constraints.txt (D303): the exact versions of every dependency for Python 3.11 — the Python of
# the site's and the agents' images. Run it on purpose (to take in updates), then let CI test the new set on 3.11
# before any deploy. Usage: bash tools/pins/make_constraints.sh
set -euo pipefail
cd "$(dirname "$0")/../.."
tmp=$(mktemp)
python -m pip install -q --dry-run --ignore-installed --python-version 3.11 --only-binary=:all: \
  --report "$tmp" ".[dev,digitize,scanner,llm,dicom,bot,agents]"
python - "$tmp" > deploy/constraints.txt <<'PY'
import datetime, json, sys
pins = {i["metadata"]["name"].lower().replace("_", "-"): i["metadata"]["version"]
        for i in json.load(open(sys.argv[1]))["install"]}
pins.pop("cardiolens", None)
print("# Exact versions for the site's and the agents' images and for the Python 3.11 CI job (D303).")
print("# Generated by tools/pins/make_constraints.sh on", datetime.date.today().isoformat(), "- do not edit by hand.")
for name in sorted(pins):
    print(f"{name}=={pins[name]}")
PY
rm -f "$tmp"
echo "deploy/constraints.txt: $(grep -c '==' deploy/constraints.txt) packages"
